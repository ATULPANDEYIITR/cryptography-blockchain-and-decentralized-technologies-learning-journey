def demonstrate_known_plaintext_property() -> None:
    print("\n=== Known-plaintext keystream relation ===")

    key = secrets.token_bytes(32)
    nonce = secrets.token_bytes(12)

    known_plaintext = b"HTTP/1.1 200 OK"
    ciphertext = ChaCha20Educational(key, nonce).crypt(known_plaintext)

    recovered_keystream = xor_bytes(known_plaintext, ciphertext)
    reconstructed = xor_bytes(b"SECRET RESPONSE", recovered_keystream)

    actual = ChaCha20Educational(key, nonce).crypt(b"SECRET RESPONSE")

    print("Recovered keystream prefix:", recovered_keystream.hex())
    print("Matches actual prefix     :", reconstructed == actual)
    assert reconstructed == actual

    print(
        "Knowing plaintext can reveal the corresponding keystream bytes. "
        "A secure stream cipher must prevent those bytes from predicting "
        "future or unrelated keystream output."
    )


# ---------------------------------------------------------------------------
# File-oriented streaming encryption
# ---------------------------------------------------------------------------

def transform_file(
    input_path: str,
    output_path: str,
    key: bytes,
    nonce: bytes,
    chunk_size: int = 64 * 1024,
) -> None:
    """
    Encrypt or decrypt a file incrementally.

    The function writes only transformed bytes. Metadata such as nonce,
    authentication tag, and protocol version would need a defined file
    format in a production implementation.
    """
    if chunk_size <= 0:
        raise ValueError("chunk_size must be positive")

    counter = 1
    pending_keystream = b""

    with open(input_path, "rb") as source, open(output_path, "wb") as target:
        while True:
            chunk = source.read(chunk_size)
            if not chunk:
                break

            stream = bytearray()

            while len(stream) < len(chunk):
                if pending_keystream:
                    take = min(len(chunk) - len(stream), len(pending_keystream))
                    stream.extend(pending_keystream[:take])
                    pending_keystream = pending_keystream[take:]
                else:
                    if counter > 0xFFFFFFFF:
                        raise OverflowError("ChaCha20 counter exhausted")
                    block = chacha20_block(key, counter, nonce)
                    counter += 1
                    take = min(len(chunk) - len(stream), len(block))
                    stream.extend(block[:take])
                    pending_keystream = block[take:]

            target.write(xor_bytes(chunk, bytes(stream)))


