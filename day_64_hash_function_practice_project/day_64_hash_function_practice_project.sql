-- Hash Functions Practice Project
-- PostgreSQL implementation using pgcrypto.
--
-- Supported database algorithms in this script:
--   SHA-256
--   SHA-512
--
-- The application implementations also demonstrate SHA-3.
-- SHA-256 and SHA-512 are used here for broad pgcrypto compatibility.
--
-- Run with a PostgreSQL role that can create the pgcrypto extension.
--
-- The schema models:
--   Artifacts
--   Approved digest algorithms
--   Immutable digest records
--   Integrity verification events
--   Latest digest and integrity reporting
--
-- pgcrypto provides digest() for unkeyed hashes and hmac() for
-- keyed message authentication. Secret HMAC keys are not stored here.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS hash_lab;

SET search_path TO hash_lab, public;


-- ============================================================
-- 1. DOMAIN TABLES
-- ============================================================

CREATE TABLE IF NOT EXISTS digest_algorithms (
    algorithm_name TEXT PRIMARY KEY,
    digest_size_bytes SMALLINT NOT NULL,

    CONSTRAINT valid_algorithm_name
        CHECK (algorithm_name IN ('sha256', 'sha512')),

    CONSTRAINT valid_digest_size
        CHECK (
            (algorithm_name = 'sha256' AND digest_size_bytes = 32)
            OR
            (algorithm_name = 'sha512' AND digest_size_bytes = 64)
        )
);


CREATE TABLE IF NOT EXISTS artifacts (
    artifact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_key TEXT NOT NULL UNIQUE,
    artifact_name TEXT NOT NULL,
    release_version TEXT NOT NULL,
    content BYTEA NOT NULL,
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT artifact_key_not_empty
        CHECK (length(trim(artifact_key)) > 0),

    CONSTRAINT artifact_name_not_empty
        CHECK (length(trim(artifact_name)) > 0),

    CONSTRAINT artifact_version_not_empty
        CHECK (length(trim(release_version)) > 0),

    CONSTRAINT artifact_created_by_not_empty
        CHECK (length(trim(created_by)) > 0)
);


CREATE TABLE IF NOT EXISTS digest_records (
    digest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    artifact_id BIGINT NOT NULL
        REFERENCES artifacts(artifact_id)
        ON DELETE RESTRICT,

    algorithm_name TEXT NOT NULL
        REFERENCES digest_algorithms(algorithm_name)
        ON DELETE RESTRICT,

    digest_value BYTEA NOT NULL,
    byte_count BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    calculated_by TEXT NOT NULL DEFAULT 'hash-lab',

    CONSTRAINT digest_byte_count_nonnegative
        CHECK (byte_count >= 0),

    CONSTRAINT digest_value_not_empty
        CHECK (octet_length(digest_value) > 0),

    CONSTRAINT calculated_by_not_empty
        CHECK (length(trim(calculated_by)) > 0),

    CONSTRAINT digest_size_matches_algorithm
        CHECK (
            (algorithm_name = 'sha256' AND octet_length(digest_value) = 32)
            OR
            (algorithm_name = 'sha512' AND octet_length(digest_value) = 64)
        )
);


CREATE TABLE IF NOT EXISTS verification_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    digest_id BIGINT NOT NULL
        REFERENCES digest_records(digest_id)
        ON DELETE RESTRICT,

    observed_digest BYTEA NOT NULL,
    observed_byte_count BIGINT NOT NULL,
    passed BOOLEAN NOT NULL,
    failure_reason TEXT,
    verifier TEXT NOT NULL,
    verified_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT observed_size_nonnegative
        CHECK (observed_byte_count >= 0),

    CONSTRAINT observed_digest_not_empty
        CHECK (octet_length(observed_digest) > 0),

    CONSTRAINT verifier_not_empty
        CHECK (length(trim(verifier)) > 0),

    CONSTRAINT valid_verification_result
        CHECK (
            (passed = TRUE AND failure_reason IS NULL)
            OR
            (
                passed = FALSE
                AND failure_reason IS NOT NULL
                AND length(trim(failure_reason)) > 0
            )
        )
);


-- ============================================================
-- 2. INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_artifacts_release
    ON artifacts (artifact_name, release_version);


CREATE INDEX IF NOT EXISTS idx_digest_artifact_algorithm_date
    ON digest_records (
        artifact_id,
        algorithm_name,
        created_at DESC,
        digest_id DESC
    );


CREATE INDEX IF NOT EXISTS idx_verification_digest_date
    ON verification_events (
        digest_id,
        verified_at DESC,
        event_id DESC
    );


CREATE INDEX IF NOT EXISTS idx_verification_failures
    ON verification_events (verified_at DESC)
    WHERE passed = FALSE;


