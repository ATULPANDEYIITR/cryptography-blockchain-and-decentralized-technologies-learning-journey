def demonstrate_validation() -> None:
    print("\n=== Validation and failure conditions ===")

    invalid_cases = [
        ("short key", lambda: ChaCha20Educational(b"x" * 31, b"y" * 12)),
        ("short nonce", lambda: ChaCha20Educational(b"x" * 32, b"y" * 11)),
        ("invalid LFSR seed", lambda: LFSR(0)),
        ("negative stream length", lambda: ChaCha20Educational(b"x" * 32, b"y" * 12).keystream(-1)),
    ]

    for name, operation in invalid_cases:
        try:
            operation()
        except (ValueError, OverflowError, TypeError) as exc:
            print(f"{name}: rejected with {type(exc).__name__}: {exc}")
        else:
            raise AssertionError(f"{name} was not rejected")


