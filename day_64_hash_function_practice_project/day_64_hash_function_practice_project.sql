-- ============================================================
-- 15. VALIDATION QUERIES
-- ============================================================

-- Report records whose stored digest length is inconsistent
-- with the approved algorithm metadata.
SELECT
    d.digest_id,
    d.algorithm_name,
    octet_length(d.digest_value) AS actual_digest_length,
    a.digest_size_bytes AS expected_digest_length
FROM digest_records AS d
JOIN digest_algorithms AS a
    ON a.algorithm_name = d.algorithm_name
WHERE octet_length(d.digest_value) <> a.digest_size_bytes;


-- Attempt an unsupported algorithm and handle the expected failure.
DO $$
DECLARE
    v_artifact_id BIGINT;
BEGIN
    SELECT artifact_id
    INTO v_artifact_id
    FROM artifacts
    WHERE artifact_key = 'payment-service:2.4.0';

    BEGIN
        PERFORM register_digest(v_artifact_id, 'md5');
    EXCEPTION
        WHEN OTHERS THEN
