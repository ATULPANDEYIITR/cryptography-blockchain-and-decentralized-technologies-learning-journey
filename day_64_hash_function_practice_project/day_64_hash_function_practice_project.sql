    END;
END;
$$;


-- ============================================================
-- 16. AGGREGATION AND REPORTING
-- ============================================================

-- Number of digest records by algorithm.
SELECT
    algorithm_name,
    COUNT(*) AS digest_record_count,
    SUM(byte_count) AS total_bytes_processed,
    ROUND(AVG(byte_count), 2) AS average_artifact_size
FROM digest_records
GROUP BY algorithm_name
ORDER BY algorithm_name;


-- Verification pass/fail statistics.
SELECT
    COUNT(*) AS total_checks,
    COUNT(*) FILTER (WHERE passed) AS successful_checks,
    COUNT(*) FILTER (WHERE NOT passed) AS failed_checks,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE passed)
        / NULLIF(COUNT(*), 0),
        2
    ) AS success_percentage
FROM verification_events;


-- Show failed integrity events.
SELECT
    a.artifact_key,
    d.algorithm_name,
    encode(ve.observed_digest, 'hex') AS observed_digest,
    ve.observed_byte_count,
    ve.failure_reason,
    ve.verifier,
    ve.verified_at
FROM verification_events AS ve
JOIN digest_records AS d
    ON d.digest_id = ve.digest_id
JOIN artifacts AS a
    ON a.artifact_id = d.artifact_id
WHERE ve.passed = FALSE
ORDER BY ve.verified_at DESC;


-- ============================================================
-- 17. WORKFLOW AND ELIGIBILITY QUERIES
-- ============================================================

-- Determine which artifacts currently match their latest
-- registered digest for the selected algorithm.
WITH latest_sha256 AS (
    SELECT DISTINCT ON (artifact_id)
        artifact_id,
        digest_id,
        digest_value,
        byte_count
    FROM digest_records
    WHERE algorithm_name = 'sha256'
    ORDER BY
        artifact_id,
        created_at DESC,
        digest_id DESC
),
current_state AS (
    SELECT
        a.artifact_id,
        a.artifact_key,
        l.digest_id,
        l.digest_value,
        public.digest(a.content, 'sha256') AS current_digest,
        octet_length(a.content) AS current_byte_count,
        l.byte_count AS registered_byte_count
    FROM artifacts AS a
    JOIN latest_sha256 AS l
        ON l.artifact_id = a.artifact_id
)
SELECT
    artifact_key,
    digest_id,
    CASE
        WHEN current_digest = digest_value
         AND current_byte_count = registered_byte_count
        THEN 'ELIGIBLE_FOR_INTEGRITY_ACCEPTANCE'
        ELSE 'REJECTED_INTEGRITY_MISMATCH'
    END AS eligibility
FROM current_state
ORDER BY artifact_key;


-- Identify artifacts that need a new digest record because
-- their content no longer matches the latest registered SHA-256.
WITH current_state AS (
    SELECT
        a.artifact_id,
        a.artifact_key,
        d.digest_value,
        d.byte_count,
        public.digest(a.content, 'sha256') AS current_digest,
        octet_length(a.content) AS current_size
    FROM artifacts AS a
    JOIN LATERAL (
        SELECT digest_value, byte_count
        FROM digest_records
        WHERE artifact_id = a.artifact_id
          AND algorithm_name = 'sha256'
        ORDER BY created_at DESC, digest_id DESC
        LIMIT 1
    ) AS d ON TRUE
)
SELECT
    artifact_key,
    CASE
        WHEN current_digest = digest_value
         AND current_size = byte_count
        THEN 'NO_ACTION_REQUIRED'
        ELSE 'RECALCULATE_AND_REVIEW'
    END AS workflow_decision
FROM current_state
ORDER BY artifact_key;


