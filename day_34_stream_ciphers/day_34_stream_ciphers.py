def run_self_checks() -> None:
    key = bytes(range(32))
    nonce = bytes(range(12))

    vector = chacha20_block(key, 1, nonce)
    assert len(vector) == 64

    plaintext = b"test stream cipher"
    ciphertext = ChaCha20Educational(key, nonce).crypt(plaintext)
    assert ChaCha20Educational(key, nonce).crypt(ciphertext) == plaintext

    chunks = [b"a", b"bc", b"defgh", b"ijklmnop" * 9]
    encrypted = list(encrypt_stream(chunks, key, nonce))
    decrypted = list(encrypt_stream(encrypted, key, nonce))
    assert b"".join(decrypted) == b"".join(chunks)

    service = HMACStreamCipher(key, b"A" * 32)
    msg = service.encrypt(b"authenticated", message_id=b"message-1")
    assert service.decrypt(msg) == b"authenticated"


