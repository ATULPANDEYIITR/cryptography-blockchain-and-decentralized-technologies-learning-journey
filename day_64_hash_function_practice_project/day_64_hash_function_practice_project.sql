-- 11. PROCESS INTEGRITY VERIFICATIONS
-- ============================================================

SELECT
    a.artifact_key,
    d.digest_id,
    d.algorithm_name,
    verify_artifact(
        a.artifact_id,
        d.digest_id,
        'scheduled-integrity-check'
    ) AS verification_passed
FROM artifacts AS a
JOIN LATERAL (
    SELECT
        digest_id,
        algorithm_name
    FROM digest_records AS dr
    WHERE dr.artifact_id = a.artifact_id
      AND dr.algorithm_name = 'sha256'
    ORDER BY
        dr.created_at DESC,
        dr.digest_id DESC
    LIMIT 1
) AS d ON TRUE
ORDER BY a.artifact_key;


-- ============================================================
-- 12. LATEST DIGEST VIEW
-- ============================================================

CREATE OR REPLACE VIEW latest_digest_records AS
SELECT DISTINCT ON (
    artifact_id,
    algorithm_name
)
    digest_id,
    artifact_id,
    algorithm_name,
    digest_value,
    byte_count,
    calculated_by,
    created_at
FROM digest_records
ORDER BY
    artifact_id,
    algorithm_name,
    created_at DESC,
    digest_id DESC;


-- ============================================================
-- 13. INTEGRITY REPORT VIEW
-- ============================================================

CREATE OR REPLACE VIEW artifact_integrity_report AS
WITH latest_events AS (
    SELECT DISTINCT ON (digest_id)
        event_id,
        digest_id,
        passed,
        failure_reason,
        verifier,
        verified_at
    FROM verification_events
    ORDER BY
        digest_id,
        verified_at DESC,
        event_id DESC
)
SELECT
    a.artifact_id,
    a.artifact_key,
    a.artifact_name,
    a.release_version,
    ld.algorithm_name,
    encode(ld.digest_value, 'hex') AS expected_digest,
    ld.byte_count AS registered_byte_count,
    le.event_id AS latest_event_id,
    le.passed AS latest_verification_passed,
    le.failure_reason,
    le.verifier,
    le.verified_at,
    CASE
        WHEN le.passed IS TRUE THEN 'VERIFIED'
        WHEN le.passed IS FALSE THEN 'FAILED'
        ELSE 'NOT_CHECKED'
    END AS integrity_status
FROM artifacts AS a
JOIN latest_digest_records AS ld
    ON ld.artifact_id = a.artifact_id
LEFT JOIN latest_events AS le
    ON le.digest_id = ld.digest_id;


