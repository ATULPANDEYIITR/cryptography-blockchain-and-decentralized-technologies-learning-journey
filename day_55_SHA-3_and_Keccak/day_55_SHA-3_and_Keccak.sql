-- SHA-3 and Keccak: PostgreSQL artifact-integrity registry.
-- Requires PostgreSQL with pgcrypto installed.
-- pgcrypto provides digest(..., 'sha3-256') only on builds that support
-- that algorithm through the underlying cryptographic library.
-- The script checks availability before inserting sample digests.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS integrity;
SET LOCAL search_path = integrity, public;

CREATE TABLE IF NOT EXISTS repositories (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_name TEXT NOT NULL UNIQUE,
    owner_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT repository_name_valid
        CHECK (length(repository_name) BETWEEN 1 AND 150),
    CONSTRAINT repository_owner_valid
        CHECK (length(owner_name) BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS artifacts (
    artifact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL
        REFERENCES repositories(repository_id) ON DELETE CASCADE,
    artifact_path TEXT NOT NULL,
    content_bytes BIGINT NOT NULL CHECK (content_bytes >= 0),
    algorithm TEXT NOT NULL DEFAULT 'SHA3-256',
    expected_digest TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT artifact_algorithm_supported
        CHECK (algorithm IN ('SHA3-224', 'SHA3-256', 'SHA3-384', 'SHA3-512')),
    CONSTRAINT artifact_digest_format
        CHECK (
            expected_digest = lower(expected_digest)
            AND expected_digest ~ '^[0-9a-f]+$'
            AND (
                (algorithm = 'SHA3-224' AND length(expected_digest) = 56)
                OR (algorithm = 'SHA3-256' AND length(expected_digest) = 64)
                OR (algorithm = 'SHA3-384' AND length(expected_digest) = 96)
                OR (algorithm = 'SHA3-512' AND length(expected_digest) = 128)
            )
        ),
    CONSTRAINT artifact_path_unique UNIQUE (repository_id, artifact_path)
);

CREATE TABLE IF NOT EXISTS verification_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_id BIGINT NOT NULL
        REFERENCES artifacts(artifact_id) ON DELETE CASCADE,
    actual_digest TEXT,
    result TEXT NOT NULL DEFAULT 'PENDING'
        CHECK (result IN ('PENDING', 'VERIFIED', 'MISMATCH', 'ERROR')),
    detail TEXT NOT NULL DEFAULT '',
    checked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT actual_digest_hex
        CHECK (
            actual_digest IS NULL
            OR actual_digest ~ '^[0-9a-f]+$'
        )
);

CREATE INDEX IF NOT EXISTS artifacts_repository_idx
    ON artifacts(repository_id);

CREATE INDEX IF NOT EXISTS verification_runs_artifact_time_idx
    ON verification_runs(artifact_id, checked_at DESC);

CREATE INDEX IF NOT EXISTS verification_runs_result_idx
    ON verification_runs(result);

-- Fail clearly when the installed pgcrypto/OpenSSL combination does not
-- provide SHA3-256. PostgreSQL cannot silently substitute legacy Keccak.
DO $$
BEGIN
    BEGIN
        PERFORM encode(digest(convert_to('abc', 'UTF8'), 'sha3-256'), 'hex');
    EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION
            'SHA3-256 is unavailable in this pgcrypto build; use an external SHA-3 provider';
    END;
END;
$$;

CREATE OR REPLACE FUNCTION calculate_sha3(
    p_content BYTEA,
    p_algorithm TEXT
)
RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
BEGIN
    IF p_algorithm NOT IN ('SHA3-224', 'SHA3-256', 'SHA3-384', 'SHA3-512') THEN
        RAISE EXCEPTION 'Unsupported SHA-3 algorithm: %', p_algorithm
            USING ERRCODE = '22023';
    END IF;

    RETURN encode(
        digest(
            p_content,
            lower(replace(p_algorithm, '-', ''))
        ),
        'hex'
    );
END;
$$;

CREATE OR REPLACE FUNCTION validate_artifact_digest()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    expected_length INTEGER;
BEGIN
    expected_length := CASE NEW.algorithm
        WHEN 'SHA3-224' THEN 56
        WHEN 'SHA3-256' THEN 64
        WHEN 'SHA3-384' THEN 96
        WHEN 'SHA3-512' THEN 128
    END;

    IF length(NEW.expected_digest) <> expected_length THEN
        RAISE EXCEPTION 'Digest length does not match algorithm %', NEW.algorithm
            USING ERRCODE = '22023';
    END IF;

    IF NEW.expected_digest <> lower(NEW.expected_digest)
       OR NEW.expected_digest !~ '^[0-9a-f]+$' THEN
        RAISE EXCEPTION 'Expected digest must be lowercase hexadecimal'
            USING ERRCODE = '22023';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS artifact_digest_guard ON artifacts;

CREATE TRIGGER artifact_digest_guard
BEFORE INSERT OR UPDATE OF algorithm, expected_digest
ON artifacts
FOR EACH ROW
EXECUTE FUNCTION validate_artifact_digest();

-- Store binary content separately in production object storage. This function
-- accepts bytes explicitly so the database does not pretend it has file access.
CREATE OR REPLACE FUNCTION record_verification(
    p_artifact_id BIGINT,
    p_content BYTEA
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    item artifacts%ROWTYPE;
    actual TEXT;
    status_value TEXT;
    new_run_id BIGINT;
BEGIN
    SELECT * INTO item
    FROM artifacts
    WHERE artifact_id = p_artifact_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown artifact ID %', p_artifact_id
            USING ERRCODE = '22023';
    END IF;

    IF octet_length(p_content)::BIGINT <> item.content_bytes THEN
        INSERT INTO verification_runs(
            artifact_id, result, detail
        )
        VALUES (
            item.artifact_id, 'ERROR',
            'Content length differs from registered metadata.'
        )
        RETURNING run_id INTO new_run_id;

        RETURN new_run_id;
    END IF;

    actual := calculate_sha3(p_content, item.algorithm);

    status_value := CASE
        WHEN actual = item.expected_digest THEN 'VERIFIED'
        ELSE 'MISMATCH'
    END;

    INSERT INTO verification_runs(
        artifact_id, actual_digest, result, detail
    )
    VALUES (
        item.artifact_id,
        actual,
        status_value,
        CASE status_value
            WHEN 'VERIFIED' THEN 'Digest matches registered value.'
            ELSE 'Digest mismatch; integrity has not been established.'
        END
    )
    RETURNING run_id INTO new_run_id;

    RETURN new_run_id;
END;
$$;

INSERT INTO repositories(repository_name, owner_name)
VALUES ('release-engine', 'platform-team')
ON CONFLICT (repository_name) DO NOTHING;

-- Deterministic sample artifacts; values are computed from their content.
INSERT INTO artifacts(
    repository_id, artifact_path, content_bytes, algorithm, expected_digest
)
SELECT r.repository_id, sample.path, octet_length(sample.content), 'SHA3-256',
       encode(digest(sample.content, 'sha3-256'), 'hex')
FROM repositories r
CROSS JOIN (
    VALUES
        ('dist/package.bin', convert_to('binary-package-v1', 'UTF8')),
        ('dist/manifest.json', convert_to('{"version":"1.0"}', 'UTF8'))
) AS sample(path, content)
WHERE r.repository_name = 'release-engine'
ON CONFLICT (repository_id, artifact_path) DO NOTHING;

-- Run the integrity checks for the registered artifacts.
DO $$
DECLARE
    item RECORD;
BEGIN
    FOR item IN
        SELECT a.artifact_id, a.artifact_path
        FROM artifacts a
        JOIN repositories r USING (repository_id)
        WHERE r.repository_name = 'release-engine'
        ORDER BY a.artifact_path
    LOOP
        IF item.artifact_path = 'dist/package.bin' THEN
            PERFORM record_verification(
                item.artifact_id,
                convert_to('binary-package-v1', 'UTF8')
            );
        ELSIF item.artifact_path = 'dist/manifest.json' THEN
            PERFORM record_verification(
                item.artifact_id,
                convert_to('{"version":"1.0"}', 'UTF8')
            );
        END IF;
    END LOOP;
END;
$$;

CREATE OR REPLACE VIEW latest_artifact_verification AS
SELECT
    r.repository_name,
    a.artifact_path,
    a.algorithm,
    a.expected_digest,
    a.content_bytes,
    v.result AS latest_result,
    v.actual_digest,
    v.checked_at
FROM artifacts a
JOIN repositories r USING (repository_id)
LEFT JOIN LATERAL (
    SELECT vr.result, vr.actual_digest, vr.checked_at
    FROM verification_runs vr
    WHERE vr.artifact_id = a.artifact_id
    ORDER BY vr.checked_at DESC, vr.run_id DESC
    LIMIT 1
) v ON TRUE;

-- Retrieval and validation report.
SELECT * FROM latest_artifact_verification
ORDER BY artifact_path;

-- Aggregation: count verified, mismatched, and failed checks.
SELECT
    result,
    count(*) AS run_count
FROM verification_runs
GROUP BY result
ORDER BY result;

-- Eligibility query: an artifact is eligible for release only if its latest
-- recorded verification succeeded.
WITH latest AS (
    SELECT DISTINCT ON (artifact_id)
        artifact_id, result, checked_at
    FROM verification_runs
    ORDER BY artifact_id, checked_at DESC, run_id DESC
)
SELECT
    a.artifact_path,
    CASE WHEN l.result = 'VERIFIED'
         THEN 'ELIGIBLE'
         ELSE 'BLOCKED'
    END AS release_eligibility
FROM artifacts a
LEFT JOIN latest l USING (artifact_id)
ORDER BY a.artifact_path;

COMMIT;
