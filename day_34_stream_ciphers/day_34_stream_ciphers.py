def benchmark_keystream() -> None:
    print("\n=== Small performance measurement ===")

    key = b"K" * 32
    nonce = b"N" * 12
    payload = b"x" * (1024 * 1024)

    cipher = ChaCha20Educational(key, nonce)
    start = time.perf_counter()
    encrypted = cipher.crypt(payload)
    elapsed = time.perf_counter() - start

    mib_per_second = (len(encrypted) / (1024 * 1024)) / max(elapsed, 1e-12)

    print(f"Processed: {len(encrypted):,} bytes")
    print(f"Elapsed  : {elapsed:.4f} seconds")
    print(f"Rate     : {mib_per_second:.2f} MiB/s")
    print(
        "This pure-Python implementation is useful for studying the algorithm, "
        "not for production throughput."
    )


