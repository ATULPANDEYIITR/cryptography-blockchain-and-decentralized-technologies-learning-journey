-- 4. IMMUTABLE DIGEST RECORDS
-- ============================================================

CREATE OR REPLACE FUNCTION reject_digest_record_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        'Digest records are immutable. Create a new record instead.';
END;
$$;


DROP TRIGGER IF EXISTS trg_digest_records_immutable
    ON digest_records;


CREATE TRIGGER trg_digest_records_immutable
BEFORE UPDATE OR DELETE
ON digest_records
FOR EACH ROW
EXECUTE FUNCTION reject_digest_record_mutation();


-- ============================================================
-- 5. REGISTER A DIGEST
-- ============================================================

CREATE OR REPLACE FUNCTION register_digest(
    p_artifact_id BIGINT,
    p_algorithm_name TEXT,
    p_calculated_by TEXT DEFAULT 'hash-lab'
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_content BYTEA;
    v_digest BYTEA;
    v_digest_id BIGINT;
    v_digest_size SMALLINT;
BEGIN
    IF p_artifact_id IS NULL THEN
        RAISE EXCEPTION 'Artifact ID cannot be null';
    END IF;

    IF p_calculated_by IS NULL OR length(trim(p_calculated_by)) = 0 THEN
        RAISE EXCEPTION 'Calculator identity cannot be empty';
    END IF;

    -- The share lock prevents an artifact update while its content is read.
    SELECT content
    INTO v_content
    FROM artifacts
    WHERE artifact_id = p_artifact_id
    FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Artifact % does not exist', p_artifact_id;
    END IF;

    SELECT digest_size_bytes
    INTO v_digest_size
    FROM digest_algorithms
    WHERE algorithm_name = p_algorithm_name;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Algorithm % is not approved', p_algorithm_name;
    END IF;

    -- digest() calculates an unkeyed cryptographic digest.
    v_digest := public.digest(v_content, p_algorithm_name);

    IF octet_length(v_digest) <> v_digest_size THEN
        RAISE EXCEPTION
            'Digest provider returned an unexpected digest length';
    END IF;

    INSERT INTO digest_records (
        artifact_id,
        algorithm_name,
        digest_value,
        byte_count,
        calculated_by
    )
    VALUES (
        p_artifact_id,
        p_algorithm_name,
        v_digest,
        octet_length(v_content),
        p_calculated_by
    )
    RETURNING digest_id INTO v_digest_id;

    RETURN v_digest_id;
END;
$$;


-- ============================================================
-- 6. VERIFY AN ARTIFACT
-- ============================================================

CREATE OR REPLACE FUNCTION verify_artifact(
    p_artifact_id BIGINT,
    p_digest_id BIGINT,
    p_verifier TEXT DEFAULT 'integrity-service'
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_content BYTEA;
    v_expected_digest BYTEA;
    v_observed_digest BYTEA;
    v_algorithm TEXT;
    v_expected_artifact_id BIGINT;
    v_passed BOOLEAN;
    v_reason TEXT;
BEGIN
    IF p_verifier IS NULL OR length(trim(p_verifier)) = 0 THEN
        RAISE EXCEPTION 'Verifier identity cannot be empty';
    END IF;

    -- Lock the artifact while reading the content being verified.
    SELECT
        a.content,
        d.digest_value,
        d.algorithm_name,
        d.artifact_id
    INTO
        v_content,
        v_expected_digest,
        v_algorithm,
        v_expected_artifact_id
    FROM digest_records AS d
    JOIN artifacts AS a
        ON a.artifact_id = d.artifact_id
    WHERE d.digest_id = p_digest_id
    FOR SHARE OF a;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Digest record % does not exist', p_digest_id;
    END IF;

    IF v_expected_artifact_id <> p_artifact_id THEN
        RAISE EXCEPTION
            'Digest record does not belong to the supplied artifact';
    END IF;

    v_observed_digest := public.digest(v_content, v_algorithm);

    v_passed := (
        v_observed_digest = v_expected_digest
        AND octet_length(v_content) = (
            SELECT byte_count
            FROM digest_records
            WHERE digest_id = p_digest_id
        )
    );

    IF NOT v_passed THEN
        v_reason := 'Digest or byte-count mismatch';
    END IF;

    INSERT INTO verification_events (
        digest_id,
        observed_digest,
        observed_byte_count,
        passed,
        failure_reason,
        verifier
    )
    VALUES (
        p_digest_id,
        v_observed_digest,
        octet_length(v_content),
        v_passed,
        v_reason,
        p_verifier
    );

    RETURN v_passed;
END;
$$;


-- ============================================================
-- 7. BATCH PROCESSING PROCEDURE
-- ============================================================

CREATE OR REPLACE PROCEDURE register_all_digests(
    p_algorithm_name TEXT,
    p_calculated_by TEXT DEFAULT 'batch-integrity-service'
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_artifact RECORD;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM digest_algorithms
        WHERE algorithm_name = p_algorithm_name
    ) THEN
        RAISE EXCEPTION
            'Algorithm % is not approved',
            p_algorithm_name;
    END IF;

    FOR v_artifact IN
        SELECT artifact_id
        FROM artifacts
        ORDER BY artifact_id
    LOOP
        PERFORM register_digest(
            v_artifact.artifact_id,
            p_algorithm_name,
            p_calculated_by
        );
    END LOOP;
END;
$$;


